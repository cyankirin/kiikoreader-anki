# 中文：联网升级的宿主测试：清单解析/版本比较（共享源），以及两块板各自的 OTA
#       任务（rc103 起 OTA 任务按板存放，没有共享的 main/ota_online.c）。
# / Host tests for online update: release parsing and version ordering (shared
#   source), plus each board's own OTA worker — since rc103 the worker lives per
#   board and there is no shared main/ota_online.c.
# 在仓库根目录运行；产物仅在 build。/ Run from the repository root; artifacts stay in build.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
mkdir -p build/ota-tests

cc_bin="${CC:-cc}"
# cJSON 由组件管理器装进 managed_components/（不进仓库）。它可能出现在仓库根
# （就地构建），也可能在 build/boards/<board>/source/ 下（build_firmware.py 会先物化板子
# 再在那里构建），因此按候选目录自动查找；KIIKO_CJSON_DIR 可显式覆盖。
# cJSON comes from the component manager, so it is absent from a clean checkout. It
# may sit at the repo root (in-place build) or under build/boards/<board>/source/
# (build_firmware.py materialises the board and builds there), so probe both.
cjson_dir="${KIIKO_CJSON_DIR:-}"
if [ -z "$cjson_dir" ]; then
    for candidate in managed_components/espressif__cjson/cJSON \
                     build/boards/*/source/managed_components/espressif__cjson/cJSON; do
        if [ -f "$candidate/cJSON.c" ]; then cjson_dir="$candidate"; break; fi
    done
    cjson_dir="${cjson_dir:-managed_components/espressif__cjson/cJSON}"
fi
cjson="$cjson_dir/cJSON.c"
if [ ! -f "$cjson" ]; then
    echo "run_ota_host_tests: cannot find $cjson" >&2
    echo "  managed_components/ is generated by the component manager. Build the" >&2
    echo "  firmware once (tools/build_firmware.py) so it lands under" >&2
    echo "  build/boards/<board>/source/, or set KIIKO_CJSON_DIR to a cJSON checkout." >&2
    exit 2
fi
common_flags=(-std=c11 -D_DEFAULT_SOURCE -Wall -Wextra -Werror -Wno-deprecated-declarations
              -Itools/ota_stubs -Imain -I"$cjson_dir")

# CI 与常规 Linux 宿主带 ASan/UBSan；运行时缺失时退化为普通构建（部分 Windows 宿主）。
# CI and regular Linux hosts carry ASan/UBSan; fall back to a plain build when
# the runtime is missing (some Windows hosts).
san_flags=()
if echo 'int main(void){return 0;}' | "$cc_bin" -fsanitize=address,undefined -x c -o /dev/null - 2>/dev/null; then
    san_flags=(-fsanitize=address,undefined -fno-omit-frame-pointer)
fi

# Windows 宿主上 cc 会在 -o 目标后补 .exe；按实际产物运行，避免误跑旧二进制。
# On Windows hosts cc appends .exe to the -o target; run the artifact actually
# produced so a stale leftover binary is not executed.
run_built() {
    local target="$1"
    if [ -x "${target}.exe" ]; then
        "${target}.exe"
    else
        "${target}"
    fi
}

# 1) 清单解析与版本比较：两块板共用同一份 main/ota_release.c。
#    Release parsing and version ordering: both boards share main/ota_release.c.
echo "== ota_release (shared) =="
"$cc_bin" "${common_flags[@]}" "${san_flags[@]}" \
    tools/ota_release_host_test.c main/ota_release.c "$cjson" \
    -lm -o build/ota-tests/ota_release
run_built build/ota-tests/ota_release

# 2) 每块板各自的 OTA 任务实现；只跑本 fork 声明支持的板（board.json 的 fork_supported）。
#    Each board's own OTA worker; only boards this fork still supports are built here.
for board in $(python -c "
import json,pathlib
for d in sorted(pathlib.Path('boards').iterdir()):
    f=d/'board.json'
    if f.is_file() and json.loads(f.read_text(encoding='utf-8')).get('fork_supported',True) is not False:
        print(d.name)
"); do
    if [ "$board" = "metalio47" ]; then
        define=1
    else
        define=0
    fi
    echo "== ota_online ($board) =="
    "$cc_bin" "${common_flags[@]}" "${san_flags[@]}" -DKIIKO_BOARD_METALIO47="$define" \
        tools/ota_online_host_test.c main/ota_release.c "$cjson" \
        -lm -pthread -o "build/ota-tests/ota_online-$board"
    run_built "build/ota-tests/ota_online-$board"
done
